-- 6d. Lineage links (entry_name / opponent stay as display snapshots)
ALTER TABLE match ADD COLUMN IF NOT EXISTS fowl_id     BIGINT;
ALTER TABLE match ADD COLUMN IF NOT EXISTS opponent_id BIGINT;

-- 6e. Backfill links ONLY on unambiguous same-user name matches (no guessing)
UPDATE match m
   SET fowl_id = sub.id
  FROM (
    SELECT user_id::text AS uid, name, min(id)::bigint AS id
      FROM fowl
     WHERE user_id IS NOT NULL AND name IS NOT NULL
     GROUP BY user_id::text, name
    HAVING count(*) = 1
  ) sub
 WHERE m.fowl_id IS NULL
   AND m.entry_name IS NOT NULL
   AND m.user_id IS NOT NULL
   AND sub.name = m.entry_name
   AND sub.uid = m.user_id::text;

UPDATE match m
   SET opponent_id = sub.id
  FROM (
    SELECT user_id::text AS uid, name, min(id)::bigint AS id
      FROM fowl
     WHERE user_id IS NOT NULL AND name IS NOT NULL
     GROUP BY user_id::text, name
    HAVING count(*) = 1
  ) sub
 WHERE m.opponent_id IS NULL
   AND m.opponent IS NOT NULL
   AND m.user_id IS NOT NULL
   AND sub.name = m.opponent
   AND sub.uid = m.user_id::text;

-- 6f. Foreign keys last (after backfill has cleaned the data)
