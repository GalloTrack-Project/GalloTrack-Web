-- 7a. fowl_status_history: reachable only through an owned bird; append-only
--     for owners (no UPDATE/DELETE policies), admin may read everything.
DROP POLICY IF EXISTS "fowl_status_history_owner_select" ON fowl_status_history;
CREATE POLICY "fowl_status_history_owner_select" ON fowl_status_history
  FOR SELECT USING (
    EXISTS (SELECT 1 FROM fowl f
             WHERE f.id = fowl_status_history.fowl_id
               AND f.user_id = auth.uid()::text)
  );

DROP POLICY IF EXISTS "fowl_status_history_owner_insert" ON fowl_status_history;
CREATE POLICY "fowl_status_history_owner_insert" ON fowl_status_history
  FOR INSERT WITH CHECK (
    EXISTS (SELECT 1 FROM fowl f
             WHERE f.id = fowl_status_history.fowl_id
               AND f.user_id = auth.uid()::text)
  );

DROP POLICY IF EXISTS "fowl_status_history_admin_select" ON fowl_status_history;
CREATE POLICY "fowl_status_history_admin_select" ON fowl_status_history
  FOR SELECT USING (
    EXISTS (SELECT 1 FROM profiles adm
             WHERE adm.id::uuid = auth.uid()
               AND (adm.is_admin = true OR adm.role = 'admin'))
  );

-- 7b. registry_options: templates for everyone, own rows editable
