  sort_order INT NOT NULL DEFAULT 0,
  is_default BOOLEAN NOT NULL DEFAULT false,
  is_active  BOOLEAN NOT NULL DEFAULT true,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE UNIQUE INDEX IF NOT EXISTS registry_options_uq
  ON registry_options (COALESCE(user_id, '~global~'), list_key, value);
CREATE INDEX IF NOT EXISTS idx_registry_options_list
  ON registry_options (list_key, sort_order);

