-- ==============================================================================
-- GALLOTRACK: M1 - REGISTRY, LIFECYCLE STATUS & CONFIGURABLE OPTION LISTS
-- (idempotent, re-run safe)
--
-- User feedback: the four status concepts must stay SEPARATE, and injured
-- birds must NEVER be converted into breeders automatically:
--   condition_status : injury/health after a match (Fit ... Deceased)
--   breeding_role    : none | breeder | material   (manual only)
--   activity_status  : active | inactive           (alive but not in use)
--   archive_kind     : sold | transfer | inactive | retired | other
--   retired_scope    : fighting | breeding | both  (picker per record)
-- `fowl.status` stays the canonical display label so existing badges/filters
-- keep working; app writes keep the new columns in sync.
--
-- Also adds:
--   fowl_status_history : append-only audit log ("status history" timeline)
--   registry_options    : user-editable lists (event/class/condition/reason/
--                         retired scope/location) with global templates
--   user_settings       : per-farm config keys (ranking metric, whether
--                         location is required, family headline count, ...)
--   match.fowl_id / match.opponent_id : lineage links (entry_name/opponent
--                         remain display snapshots)
-- ==============================================================================

-- ═══════════════════════════════════════════════════════════════════════════
-- 1. fowl: new orthogonal lifecycle columns
-- ═══════════════════════════════════════════════════════════════════════════

ALTER TABLE fowl ADD COLUMN IF NOT EXISTS notes           TEXT;
ALTER TABLE fowl ADD COLUMN IF NOT EXISTS condition_status TEXT NOT NULL DEFAULT 'Fit / Recovered';
ALTER TABLE fowl ADD COLUMN IF NOT EXISTS breeding_role   TEXT NOT NULL DEFAULT 'none';
ALTER TABLE fowl ADD COLUMN IF NOT EXISTS activity_status TEXT NOT NULL DEFAULT 'active';
ALTER TABLE fowl ADD COLUMN IF NOT EXISTS archive_kind    TEXT;
ALTER TABLE fowl ADD COLUMN IF NOT EXISTS retired_scope   TEXT;
ALTER TABLE fowl ADD COLUMN IF NOT EXISTS return_date     DATE;

-- ═══════════════════════════════════════════════════════════════════════════
-- 2. Backfill from existing registry state (run once, but re-run safe:
--    every UPDATE only touches rows that still look unmigrated)
-- ═══════════════════════════════════════════════════════════════════════════

-- 2a. Archived birds -> structured archive kind (free-text reason preserved)
UPDATE fowl SET archive_kind = CASE
    WHEN lower(COALESCE(archive_reason, '')) LIKE 'sold%'      THEN 'sold'
    WHEN lower(COALESCE(archive_reason, '')) LIKE 'transfer%'  THEN 'transfer'
    WHEN lower(COALESCE(archive_reason, '')) LIKE 'inactive%'  THEN 'inactive'
    WHEN lower(COALESCE(archive_reason, '')) LIKE 'retired%'   THEN 'retired'
    WHEN btrim(COALESCE(archive_reason, '')) <> ''             THEN 'other'
    ELSE NULL
  END
  WHERE status = 'Archived' AND archive_kind IS NULL;

-- 2b. Retired birds -> which career ended (fighting / breeding)
UPDATE fowl SET retired_scope = CASE
    WHEN lower(COALESCE(archive_reason, '')) LIKE 'retired from breeding%' THEN 'breeding'
    ELSE 'fighting'
  END
  WHERE archive_kind = 'retired' AND retired_scope IS NULL;

-- 2c. Deceased birds -> injury condition agrees with lifecycle (atomic by app)
UPDATE fowl SET condition_status = 'Deceased'
  WHERE status = 'Deceased' AND condition_status <> 'Deceased';

-- 2d. 'Sire Material' (legacy status) -> breeding role, still active
UPDATE fowl SET breeding_role = 'material'
  WHERE status = 'Sire Material' AND breeding_role = 'none';

-- 2e. Not-in-use birds -> inactive activity
UPDATE fowl SET activity_status = 'inactive'
  WHERE status IN ('Archived', 'Inactive', 'Deceased') AND activity_status = 'active';

-- 2f. Structural enums get a CHECK (only after the data is clean)
ALTER TABLE fowl DROP CONSTRAINT IF EXISTS fowl_breeding_role_check;
ALTER TABLE fowl
  ADD CONSTRAINT fowl_breeding_role_check CHECK (breeding_role IN ('none', 'breeder', 'material'));

ALTER TABLE fowl DROP CONSTRAINT IF EXISTS fowl_activity_status_check;
ALTER TABLE fowl
  ADD CONSTRAINT fowl_activity_status_check CHECK (activity_status IN ('active', 'inactive'));

-- No CHECK on condition_status / archive_kind / retired_scope: those come from
-- the editable registry_options lists (history rows must always be storable).

-- ═══════════════════════════════════════════════════════════════════════════
-- 3. fowl_status_history - append-only status change log
-- ═══════════════════════════════════════════════════════════════════════════

CREATE TABLE IF NOT EXISTS fowl_status_history (
  id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  fowl_id    BIGINT NOT NULL REFERENCES fowl(id) ON DELETE CASCADE,
  field      TEXT NOT NULL,               -- status | condition_status | breeding_role | activity_status | archive_kind | retired_scope
  old_value  TEXT,
  new_value  TEXT NOT NULL,
  reason     TEXT,                        -- archive / death reason label
  note       TEXT,
  changed_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  changed_by UUID                         -- auth.uid() of the editor
);

CREATE INDEX IF NOT EXISTS idx_fowl_status_history_fowl
  ON fowl_status_history (fowl_id, changed_at DESC);

-- 3a. One backfilled entry per existing bird (current registry state)
INSERT INTO fowl_status_history (fowl_id, field, old_value, new_value, reason, note, changed_at)
SELECT f.id, 'status', NULL, f.status,
       COALESCE(NULLIF(btrim(f.archive_reason), ''), NULLIF(btrim(f.death_reason), '')),
       'Backfilled from registry state (migration 20261006)',
       COALESCE(f.created_at, now())
  FROM fowl f
 WHERE NOT EXISTS (
   SELECT 1 FROM fowl_status_history h WHERE h.fowl_id = f.id
 );

-- ═══════════════════════════════════════════════════════════════════════════
-- 4. registry_options - user-editable lists
--    user_id IS NULL = global template (read-only for users);
--    user_id set     = farm's own entries ("Add Other" / edits).
--    Deactivate (is_active=false) instead of deleting once an option is used.
-- ═══════════════════════════════════════════════════════════════════════════

CREATE TABLE IF NOT EXISTS registry_options (
  id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id    TEXT,                        -- NULL = global template
  list_key   TEXT NOT NULL,               -- event_type | bird_class | post_match_condition | archive_reason | death_reason | retired_scope | location | match_type
