-- ==============================================================================
-- GALLOTRACK: MILESTONE NOTIFICATIONS
-- ==============================================================================
-- In-app only. Insertions are performed by the scheduled cron route with the
-- service role. Owners may read their own rows and update read_at only.
--
-- REVIEW BEFORE APPLY: this migration intentionally does not run in production
-- until the migration review is approved.
-- ==============================================================================

CREATE TABLE IF NOT EXISTS public.notifications (
  id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id     UUID NOT NULL DEFAULT auth.uid() REFERENCES auth.users(id) ON DELETE CASCADE,
  type        TEXT NOT NULL CHECK (type IN ('stage_changed', 'fully_mature', 'stage_upcoming')),
  fowl_id     BIGINT NOT NULL REFERENCES public.fowl(id) ON DELETE CASCADE,
  stage       TEXT NOT NULL,
  title       TEXT NOT NULL,
  body        TEXT NOT NULL,
  due_date    DATE NOT NULL,
  read_at     TIMESTAMPTZ,
  created_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
  CONSTRAINT notifications_user_fowl_type_stage_key
    UNIQUE (user_id, fowl_id, type, stage)
);

CREATE INDEX IF NOT EXISTS idx_notifications_user_created
  ON public.notifications (user_id, created_at DESC);

CREATE INDEX IF NOT EXISTS idx_notifications_user_unread
  ON public.notifications (user_id, created_at DESC)
  WHERE read_at IS NULL;

ALTER TABLE public.notifications ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "notifications_owner_select" ON public.notifications;
CREATE POLICY "notifications_owner_select" ON public.notifications
  FOR SELECT TO authenticated
  USING (user_id = auth.uid());

DROP POLICY IF EXISTS "notifications_owner_update" ON public.notifications;
CREATE POLICY "notifications_owner_update" ON public.notifications
  FOR UPDATE TO authenticated
  USING (user_id = auth.uid())
  WITH CHECK (user_id = auth.uid());

-- Explicit grants: owners can read and mark read, but cannot insert or delete.
REVOKE ALL ON public.notifications FROM anon;
REVOKE ALL ON public.notifications FROM authenticated;
GRANT SELECT ON public.notifications TO authenticated;
GRANT UPDATE (read_at) ON public.notifications TO authenticated;
GRANT ALL ON public.notifications TO service_role;
GRANT USAGE, SELECT ON SEQUENCE public.notifications_id_seq TO service_role;

-- A birth-date edit invalidates unread upcoming notices. The daily job
-- recomputes and recreates any that are still valid. Archiving/deceasing a
-- chicken also clears its unread upcoming notices.
CREATE OR REPLACE FUNCTION public.invalidate_unread_milestone_notifications()
RETURNS TRIGGER AS $$
BEGIN
  IF NEW.birthdate IS DISTINCT FROM OLD.birthdate THEN
    DELETE FROM public.notifications
     WHERE fowl_id = NEW.id
       AND type = 'stage_upcoming'
       AND read_at IS NULL;
  END IF;

  IF NEW.status IS DISTINCT FROM OLD.status
     AND lower(coalesce(NEW.status, '')) IN ('archived', 'deceased') THEN
    DELETE FROM public.notifications
     WHERE fowl_id = NEW.id
       AND type = 'stage_upcoming'
       AND read_at IS NULL;
  END IF;

  RETURN NEW;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER SET search_path = public;

DROP TRIGGER IF EXISTS invalidate_unread_milestone_notifications_trigger ON public.fowl;
CREATE TRIGGER invalidate_unread_milestone_notifications_trigger
  AFTER UPDATE OF birthdate, status ON public.fowl
  FOR EACH ROW
  EXECUTE FUNCTION public.invalidate_unread_milestone_notifications();

COMMENT ON TABLE public.notifications IS
  'In-app milestone notifications generated by the daily service-role cron job.';
COMMENT ON COLUMN public.notifications.read_at IS
  'Set by the owner when the notification is read; NULL means unread.';

